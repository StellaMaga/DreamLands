    public class DialogueNode
    {
        public string Speaker;          // 발화자
        public string Text;             // 내용

        // 화자가 있는 지문
        public DialogueNode(string speaker, string text)
        {
            Speaker = Game_System.ColorSpeaker(speaker);
            Text = text;
        }

        // 화자가 없는 지문
        public DialogueNode(string text)
        {
            Speaker = "";
            Text = text;
        }
    }

